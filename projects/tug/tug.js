// The derelicts, handed out round the levels so every design turns up; the
// two tugs are konex's.
const DERELICTS = [["conex", "dart"], ["conex", "necromancer"], ["conex", "tomaquad"], ["conex", "defender"], ["conex", "gryphon"],
  ["conex", "trident"], ["conex", "yodacon"], ["override", "callisto"], ["conex", "large-pin"], ["override", "yodacon"]];
const TUGS = [["konex", "citrus"], ["konex", "advisor"]];

const state = { phase: "loading", level: 0, tug: 0, me: null, hulls: [], goals: new Set(), walls: new Set(), cols: 0, rows: 0,
  moves: 0, pushes: 0, pulls: PULLS, history: [], anim: 0, t: 0 };
let art = {};
const key = (x, y) => `${x},${y}`;

function load() { try { return JSON.parse(localStorage.getItem(SAVE)) ?? {}; } catch { return {}; } }
function save(d) { try { localStorage.setItem(SAVE, JSON.stringify(d)); } catch { /* not kept */ } }
const nameOf = ([ed, slug]) => (ed === "override" && slug === "yodacon" ? "1998 Yodacon" : art[`${ed}/${slug}`].name);

function hullLength(ship) {
  const r = frameRect(ship, 0), c = new OffscreenCanvas(r.w, r.h), g = c.getContext("2d");
  g.drawImage(ship.sheet, r.x, r.y, r.w, r.h, 0, 0, r.w, r.h);
  const a = g.getImageData(0, 0, r.w, r.h).data;
  let lo = r.h, hi = 0;
  for (let y = 0; y < r.h; y++) for (let x = 0; x < r.w; x++) if (a[(y * r.w + x) * 4 + 3] > 40) { lo = Math.min(lo, y); hi = Math.max(hi, y); }
  return hi - lo + 1;
}

// --- The yard ------------------------------------------------------------------------------------

function startLevel(n = state.level) {
  const L = LEVELS[n];
  state.level = n;
  state.rows = L.rows.length; state.cols = Math.max(...L.rows.map((r) => r.length));
  state.walls = new Set(); state.goals = new Set(); state.hulls = [];
  L.rows.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === "#") state.walls.add(key(x, y));
    if (c === "." || c === "*") state.goals.add(key(x, y));
    if (c === "$" || c === "*") {
      const which = DERELICTS[(n * 3 + state.hulls.length) % DERELICTS.length];
      state.hulls.push({ x, y, px: x, py: y, which, ship: art[`${which[0]}/${which[1]}`], name: nameOf(which),
        heading: ((n * 7 + state.hulls.length * 13) % 36) * 10, turnFrom: null });
    }
    if (c === "@") state.me = { x, y, px: x, py: y, heading: 90 };
  }));
  Object.assign(state, { phase: "play", moves: 0, pushes: 0, pulls: PULLS, history: [], anim: 0 });
  $("banner").hidden = true;
  renderSide();
}

const hullAt = (x, y) => state.hulls.find((h) => h.x === x && h.y === y);
const blocked = (x, y) => state.walls.has(key(x, y)) || !!hullAt(x, y);
const solved = () => state.hulls.every((h) => state.goals.has(key(h.x, h.y)));

// One step. A hull ahead is pushed if the cell past it is clear. With `pull`
// (Shift held) and a pull left, a hull behind you comes along.
function move(dir, pull = false) {
  if (state.phase !== "play" || !DIRS[dir]) return false;
  const [dx, dy, heading] = DIRS[dir], me = state.me, nx = me.x + dx, ny = me.y + dy;
  if (state.walls.has(key(nx, ny))) { me.heading = heading; return false; }
  const ahead = hullAt(nx, ny);
  if (ahead && blocked(nx + dx, ny + dy)) { me.heading = heading; play("error"); return false; }
  const behind = pull && state.pulls > 0 && !ahead ? hullAt(me.x - dx, me.y - dy) : null;
  state.history.push({ me: { ...me }, hulls: state.hulls.map((h) => ({ x: h.x, y: h.y, heading: h.heading })), moves: state.moves,
    pushes: state.pushes, pulls: state.pulls });
  for (const h of state.hulls) { h.px = h.x; h.py = h.y; h.turnFrom = null; }
  me.px = me.x; me.py = me.y;
  me.x = nx; me.y = ny;
  // A pull keeps your heading (you back away); otherwise you face the move.
  if (!behind) me.heading = heading;
  state.moves++;
  if (ahead) {
    ahead.turnFrom = ahead.heading; ahead.heading = heading;
    ahead.x += dx; ahead.y += dy; state.pushes++;
    play(state.goals.has(key(ahead.x, ahead.y)) ? "pickup" : "select");
  }
  if (behind) {
    behind.turnFrom = behind.heading; behind.heading = heading;
    behind.x += dx; behind.y += dy; state.pulls--;
    play("target");
  }
  state.anim = SLIDE;
  if (solved()) win();
  renderSide();
  return true;
}

function undo() {
  const last = state.history.pop();
  if (!last || (state.phase !== "play" && state.phase !== "won")) return false;
  Object.assign(state.me, last.me, { px: last.me.x, py: last.me.y });
  last.hulls.forEach((h, i) => Object.assign(state.hulls[i], h, { px: h.x, py: h.y, turnFrom: null }));
  Object.assign(state, { moves: last.moves, pushes: last.pushes, pulls: last.pulls, phase: "play", anim: 0 });
  $("banner").hidden = true;
  play("cancel");
  renderSide();
  return true;
}

function win() {
  state.phase = "won";
  const L = LEVELS[state.level], best = load(), mine = best[state.level];
  const record = !mine || state.pushes < mine.pushes || (state.pushes === mine.pushes && state.moves < mine.moves);
  if (record) save({ ...best, [state.level]: { moves: state.moves, pushes: state.pushes, pulls: PULLS - state.pulls } });
  play("won");
  $("banner-title").textContent = state.level === LEVELS.length - 1 ? "Yard cleared" : "All berthed";
  $("banner-text").textContent = `${L.name}: ${state.moves} moves, ${state.pushes} pushes (par ${L.par})` +
    `${state.pulls < PULLS ? `, ${PULLS - state.pulls} pull${PULLS - state.pulls > 1 ? "s" : ""}` : ""}. ` +
    (state.level < LEVELS.length - 1 ? "Enter for the next yard." : "Every yard done.");
  $("banner").hidden = false;
}

// --- Drawing -------------------------------------------------------------------------------------

function layout() {
  const tile = Math.floor(Math.min(64, (W - 20) / state.cols, (H - 20) / state.rows));
  return { tile, ox: Math.floor((W - tile * state.cols) / 2), oy: Math.floor((H - tile * state.rows) / 2) };
}

function draw() {
  ctx.fillStyle = "#04070c"; ctx.fillRect(0, 0, W, H);
  if (!state.me) return;
  const { tile, ox, oy } = layout(), f = state.anim > 0 ? 1 - state.anim / SLIDE : 1;
  const at = (o) => [ox + (o.px + (o.x - o.px) * f + 0.5) * tile, oy + (o.py + (o.y - o.py) * f + 0.5) * tile];
  // Deck plates inside, bulkheads outside.
  for (let y = 0; y < state.rows; y++) for (let x = 0; x < state.cols; x++) {
    const px = ox + x * tile, py = oy + y * tile;
    if (state.walls.has(key(x, y))) {
      if (!inside(x, y)) continue;
      const g = ctx.createLinearGradient(px, py, px + tile, py + tile);
      g.addColorStop(0, "#56606c"); g.addColorStop(1, "#262c34");
      ctx.fillStyle = g; ctx.fillRect(px, py, tile, tile);
      ctx.strokeStyle = "#11151a"; ctx.strokeRect(px + 0.5, py + 0.5, tile - 1, tile - 1);
      ctx.fillStyle = "#7d8894";
      for (const [a, b] of [[0.15, 0.15], [0.85, 0.15], [0.15, 0.85], [0.85, 0.85]]) ctx.fillRect(px + a * tile - 1, py + b * tile - 1, 2, 2);
    } else {
      ctx.fillStyle = (x + y) % 2 ? "#0d141c" : "#0b1118"; ctx.fillRect(px, py, tile, tile);
      ctx.strokeStyle = "rgb(120 160 200 / 0.08)"; ctx.strokeRect(px + 0.5, py + 0.5, tile - 1, tile - 1);
    }
  }
  // Berths: a lit outline with corner chevrons; brighter with a hull in it.
  for (const g of state.goals) {
    const [x, y] = g.split(",").map(Number), px = ox + x * tile, py = oy + y * tile, full = !!hullAt(x, y);
    ctx.strokeStyle = full ? "#7ef0a8" : `rgb(126 240 168 / ${0.45 + 0.25 * Math.sin(state.t * 4)})`;
    ctx.lineWidth = 2; ctx.setLineDash([6, 4]);
    ctx.strokeRect(px + 4, py + 4, tile - 8, tile - 8);
    ctx.setLineDash([]);
    if (full) { ctx.fillStyle = "rgb(126 240 168 / 0.12)"; ctx.fillRect(px + 4, py + 4, tile - 8, tile - 8); }
  }
  ctx.lineWidth = 1;
  // Derelicts are drawn a little dark until berthed: dead in the water.
  for (const h of state.hulls) {
    const [x, y] = at(h), heading = h.turnFrom == null || f >= 1 ? h.heading : turnBetween(h.turnFrom, h.heading, f);
    ctx.filter = state.goals.has(key(h.x, h.y)) ? "none" : "brightness(0.7) saturate(0.6)";
    drawShip(ctx, h.ship, heading, x, y, (tile * 0.82) / h.ship.len);
  }
  ctx.filter = "none";
  const me = state.me, [mx, my] = at(me), tug = art[`${TUGS[state.tug][0]}/${TUGS[state.tug][1]}`];
  if (held.has("Shift") && state.pulls > 0 && state.phase === "play") {
    ctx.strokeStyle = "rgb(180 155 255 / 0.7)"; ctx.beginPath(); ctx.arc(mx, my, tile * 0.45, 0, Math.PI * 2); ctx.stroke();
  }
  const glow = ctx.createRadialGradient(mx, my, 0, mx, my, tile * 0.5);
  glow.addColorStop(0, "rgb(107 198 255 / 0.35)"); glow.addColorStop(1, "rgb(107 198 255 / 0)");
  ctx.fillStyle = glow; ctx.fillRect(mx - tile / 2, my - tile / 2, tile, tile);
  drawShip(ctx, tug, me.heading, mx, my, (tile * 0.62) / tug.len);
}

// The heading part-way through a turn, the short way round.
const turnBetween = (a, b, f) => { const d = ((b - a + 540) % 360) - 180; return (a + d * f + 360) % 360; };

// A bulkhead cell is drawn only if it touches the yard, so the outline follows
// the shape of the room rather than filling its bounding box.
function inside(x, y) {
  for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
    const k = key(x + dx, y + dy);
    if ((dx || dy) && x + dx >= 0 && y + dy >= 0 && x + dx < state.cols && y + dy < state.rows && !state.walls.has(k) && reach.has(k)) return true;
  }
  return false;
}
let reach = new Set();
function computeReach() {
  reach = new Set([key(state.me.x, state.me.y)]);
  const q = [[state.me.x, state.me.y]];
  while (q.length) {
    const [x, y] = q.pop();
    for (const [dx, dy] of Object.values(DIRS)) {
      const k = key(x + dx, y + dy);
      if (!state.walls.has(k) && !reach.has(k) && x + dx >= 0 && y + dy >= 0 && x + dx < state.cols && y + dy < state.rows) { reach.add(k); q.push([x + dx, y + dy]); }
    }
  }
}

function renderSide() {
  const L = LEVELS[state.level];
  $("level").textContent = `${state.level + 1}/${LEVELS.length}`;
  $("moves").textContent = state.moves;
  $("pushes").textContent = `${state.pushes}/${L.par}`;
  $("pulls").textContent = state.pulls;
  $("yard-name").textContent = L.name;
  $("derelicts").textContent = `In the yard: ${state.hulls.map((h) => h.name).join(", ")}.`;
  const best = load();
  const unlocked = Math.min(LEVELS.length - 1, Math.max(0, ...Object.keys(best).map((k) => Number(k) + 1)));
  $("levels").replaceChildren(...LEVELS.map((lv, i) => {
    const b = document.createElement("button");
    b.type = "button"; b.className = `yc-plate lv${i === state.level ? " on" : ""}${best[i] ? " done" : ""}`;
    b.textContent = best[i] ? `${i + 1}✓` : i + 1; b.title = `${lv.name}${best[i] ? ` — best ${best[i].pushes} pushes` : ""}`;
    b.disabled = i > unlocked && !unlockAll;
    b.setAttribute("aria-label", `Yard ${i + 1}: ${b.title}`);
    b.addEventListener("click", () => { startLevel(i); computeReach(); });
    return b;
  }));
}
let unlockAll = new URLSearchParams(location.search).has("all");

// --- Input ---------------------------------------------------------------------------------------

const held = new Set();
const KEYS = { ArrowUp: "up", w: "up", ArrowDown: "down", s: "down", ArrowLeft: "left", a: "left", ArrowRight: "right", d: "right" };
addEventListener("keydown", (e) => {
  const k = e.key.length === 1 ? e.key.toLowerCase() : e.key;
  if (e.target.closest?.("button") && (k === " " || k === "Enter")) return;
  if (k === "Shift") held.add("Shift");
  if (KEYS[k]) { e.preventDefault(); move(KEYS[k], e.shiftKey || pullArmed); if (pullArmed) setPull(false); }
  if (k === "z" || k === "u" || k === "Backspace") { e.preventDefault(); undo(); }
  if (k === "r") { startLevel(); computeReach(); }
  if (k === "Enter" && state.phase === "won" && state.level < LEVELS.length - 1) { startLevel(state.level + 1); computeReach(); }
});
addEventListener("keyup", (e) => { if (e.key === "Shift") held.delete("Shift"); });
addEventListener("blur", () => held.clear());
// On a touch screen the PULL button arms one pull for the next move.
let pullArmed = false;
function setPull(on) { pullArmed = on && state.pulls > 0; $("pull").setAttribute("aria-pressed", String(pullArmed)); if (pullArmed) held.add("Shift"); else held.delete("Shift"); }
for (const b of document.querySelectorAll("[data-pad]")) {
  b.addEventListener("click", () => {
    const p = b.dataset.pad;
    if (p === "pull") return setPull(!pullArmed);
    if (p === "undo") return undo();
    move(p, pullArmed); if (pullArmed) setPull(false);
  });
}
let swipe = null;
canvas.addEventListener("pointerdown", (e) => { swipe = [e.clientX, e.clientY]; });
canvas.addEventListener("pointerup", (e) => {
  if (!swipe) return;
  const dx = e.clientX - swipe[0], dy = e.clientY - swipe[1];
  if (Math.hypot(dx, dy) > 14) { move(Math.abs(dx) > Math.abs(dy) ? (dx > 0 ? "right" : "left") : dy > 0 ? "down" : "up", pullArmed); if (pullArmed) setPull(false); }
  swipe = null;
});

